  async processManualPayment(
    userId: string,
    dto: CreateManualPaymentDto,
    idempotencyKey?: string,
  ) {
    this.logger.log(
      `Processing manual payment for user: ${userId} - Amount: ${dto.amount} Kobo`,
    );

    // If idempotency key is provided, validate it
    if (idempotencyKey) {
      const isValid = await this.validateIdempotencyKey(idempotencyKey, userId);
      if (!isValid) {
        throw new BadRequestException(
          'Invalid or expired idempotency key. Please generate a new one.',
        );
      }
    }

    return this.idempotencyService.processWithIdempotency(
      idempotencyKey,
      userId,
      async () => {
        const result = await this.executeManualPayment(
          userId,
          dto,
          idempotencyKey,
        );
        // Mark the idempotency key as used
        if (idempotencyKey) {
          await this.markIdempotencyKeyAsUsed(idempotencyKey);
        }
        return result;
      },
    );
  }

  private async executeManualPayment(
    userId: string,
    dto: CreateManualPaymentDto,
    idempotencyKey?: string,
  ) {
    const user = await this.prisma.user.findUnique({
      where: { id: userId },
      include: { studentProfile: true },
    });
    if (!user) {
      throw new NotFoundException('User not found');
    }

    const wallet = await this.walletService.getOrCreateWallet({
      type: 'USER',
      id: userId,
    });

    const orgWallet = await this.walletService.getOrCreateWallet({
      type: 'ORGANIZATION',
      id: dto.organizationId,
    });

    const result = await this.prisma.$transaction(async (tx) => {
      if (wallet.status !== 'ACTIVE') {
        throw new BadRequestException('Wallet is not active');
      }

      if (wallet.balance < dto.amount) {
        throw new BadRequestException('Insufficient balance');
      }

      const walletBalanceBefore = wallet.balance;
      const walletBalanceAfter = walletBalanceBefore - dto.amount;

      const reference =
        dto.reference || `PAY_${randomBytes(16).toString('hex').toUpperCase()}`;

      const transaction = await tx.transaction.create({
        data: {
          walletId: wallet.id,
          type: 'DEBIT',
          amount: dto.amount,
          fee: 0,
          netAmount: dto.amount,
          status: 'COMPLETED',
          reference,
          description: dto.description,
          completedAt: new Date(),
          metadata: {
            idempotencyKey: idempotencyKey,
          },
        },
      });

      await tx.ledgerEntry.create({
        data: {
          accountId: wallet.ledgerAccountId!,
          transactionId: transaction.id,
          amount: dto.amount,
          type: 'DEBIT',
          balanceBefore: walletBalanceBefore,
          balanceAfter: walletBalanceAfter,
          description: dto.description,
        },
      });

      await tx.wallet.update({
        where: { id: wallet.id },
        data: { balance: walletBalanceAfter },
      });

      await tx.ledgerAccount.update({
        where: { id: wallet.ledgerAccountId! },
        data: { balance: walletBalanceAfter },
      });

      const serviceFee = 0;
      const netAmount = dto.amount - serviceFee;
      const orgWalletBalanceBefore = orgWallet.balance;
      const orgWalletBalanceAfter = orgWalletBalanceBefore + netAmount;

      await tx.ledgerEntry.create({
        data: {
          accountId: orgWallet.ledgerAccountId!,
          transactionId: transaction.id,
          amount: netAmount,
          type: 'CREDIT',
          balanceBefore: orgWalletBalanceBefore,
          balanceAfter: orgWalletBalanceAfter,
          description: dto.description,
        },
      });

      await tx.wallet.update({
        where: { id: orgWallet.id },
        data: { balance: orgWalletBalanceAfter },
      });

      await tx.ledgerAccount.update({
        where: { id: orgWallet.ledgerAccountId! },
        data: { balance: orgWalletBalanceAfter },
      });

      const payment = await tx.payment.create({
        data: {
          payerId: userId,
          organizationId: dto.organizationId,
          transactionId: transaction.id,
          amount: dto.amount,
          serviceFee: serviceFee,
          status: 'COMPLETED',
          paymentMethod: dto.paymentMethod as any,
          reference,
          description: dto.description,
          paidAt: new Date(),
          metadata: {
            category: dto.category || 'OTHER',
            categoryId: dto.categoryId,
            manualPayment: true,
            idempotencyKey: idempotencyKey,
          },
        },
      });

      const journalLines = [
        {
          accountId: wallet.ledgerAccountId!,
          type: 'DEBIT' as const,
          amount: dto.amount,
          description: `Manual payment from user ${userId}`,
        },
        {
          accountId: orgWallet.ledgerAccountId!,
          type: 'CREDIT' as const,
          amount: netAmount,
          description: `Manual payment to organization ${dto.organizationId}`,
        },
      ];

      if (serviceFee > 0) {
        const platformFeeAccount =
          await this.ledgerService.getOrCreatePlatformFeeAccount();
        journalLines.push({
          accountId: platformFeeAccount.id,
          type: 'CREDIT' as const,
          amount: serviceFee,
          description: 'Platform service fee',
        });
      }

      const journalEntry = await this.ledgerService.createJournalEntry({
        lines: journalLines,
        description: `Manual payment: ${dto.description}`,
        paymentId: payment.id,
        transactionId: transaction.id,
        createdBy: userId,
      });

      await tx.payment.update({
        where: { id: payment.id },
        data: { journalEntryId: journalEntry.id },
      });

      await tx.transaction.update({
        where: { id: transaction.id },
        data: { journalEntryId: journalEntry.id },
      });

      if (dto.dueAssignmentId) {
        await this.handleDuePayment(
          tx,
          dto.dueAssignmentId,
          payment.id,
          dto.amount,
        );
      }

      await tx.activityLog.create({
        data: {
          userId,
          activity: 'MANUAL_PAYMENT',
          details: JSON.stringify({
            paymentId: payment.id,
            amount: dto.amount,
            reference,
            organizationId: dto.organizationId,
            category: dto.category || 'OTHER',
            journalEntryId: journalEntry.id,
            idempotencyKey: idempotencyKey,
          }),
        },
      });

      this.eventService.emitPaymentReceived({
        paymentId: payment.id,
        userId: userId,
        organizationId: dto.organizationId,
        amount: dto.amount,
        reference: reference,
        metadata: {
          category: dto.category || 'OTHER',
          manualPayment: true,
          idempotencyKey: idempotencyKey,
        },
      });

      await this.walletService.invalidateWalletCache({
        type: 'USER',
        id: userId,
      });
      await this.walletService.invalidateWalletCache({
        type: 'ORGANIZATION',
        id: dto.organizationId,
      });

      this.logger.log(
        `Manual payment processed: ${payment.id} - ${dto.amount} Kobo (₦${(dto.amount / this.KOBO_PER_NAIRA).toFixed(2)})`,
      );

      return {
        payment,
        transaction,
        journalEntry,
        balance: walletBalanceAfter,
        idempotencyKey: idempotencyKey,
      };
    });

    try {
      await this.receiptService.generateReceiptFromPayment(
        result.payment.id,
        userId,
      );
      this.logger.log(`Receipt generated for payment ${result.payment.id}`);
    } catch (error: any) {
      this.logger.error(
        `Failed to generate receipt for payment ${result.payment.id}: ${error.message}`,
      );
    }

    return result;
  }

