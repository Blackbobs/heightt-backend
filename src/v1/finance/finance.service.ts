  async creditWallet(userId: string, dto: CreditWalletDto) {
    this.logger.log(
      `Crediting wallet for user: ${dto.userId} - Amount: ${dto.amount} Kobo`,
    );

    const wallet = await this.walletService.getOrCreateWallet({
      type: 'USER',
      id: dto.userId,
    });

    return this.prisma.$transaction(async (tx) => {
      if (wallet.status !== 'ACTIVE') {
        throw new BadRequestException('Wallet is not active');
      }

      const balanceBefore = wallet.balance;
      const balanceAfter = balanceBefore + dto.amount;

      const transaction = await tx.transaction.create({
        data: {
          walletId: wallet.id,
          type: 'CREDIT',
          amount: dto.amount,
          fee: 0,
          netAmount: dto.amount,
          status: 'COMPLETED',
          reference:
            dto.reference ||
            `TXN_${randomBytes(16).toString('hex').toUpperCase()}`,
          description: dto.description || 'Wallet credit',
          completedAt: new Date(),
        },
      });

      await tx.ledgerEntry.create({
        data: {
          accountId: wallet.ledgerAccountId!,
          transactionId: transaction.id,
          amount: dto.amount,
          type: 'CREDIT',
          balanceBefore,
          balanceAfter,
          description: dto.description || 'Wallet credit',
        },
      });

      const updatedWallet = await tx.wallet.update({
        where: { id: wallet.id },
        data: { balance: balanceAfter },
      });

      await tx.ledgerAccount.update({
        where: { id: wallet.ledgerAccountId! },
        data: { balance: balanceAfter },
      });

      await tx.activityLog.create({
        data: {
          userId,
          activity: 'WALLET_CREDITED',
          details: JSON.stringify({
            walletId: wallet.id,
            amount: dto.amount,
            balanceAfter,
            reference: transaction.reference,
          }),
        },
      });

      this.eventService.emitWalletCredited({
        walletId: wallet.id,
        userId: dto.userId,
        amount: dto.amount,
        balance: balanceAfter,
        previousBalance: balanceBefore,
        reference: transaction.reference,
        description: dto.description || 'Wallet credit',
      });

      await this.walletService.invalidateWalletCache({
        type: 'USER',
        id: dto.userId,
      });

      this.logger.log(
        `Wallet credited: ${wallet.id}, amount: ${dto.amount} Kobo (₦${(dto.amount / this.KOBO_PER_NAIRA).toFixed(2)})`,
      );
      return {
        wallet: updatedWallet,
        transaction,
      };
    });
  }

