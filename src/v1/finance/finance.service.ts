  async getFinancialOverview(institutionId?: string) {
    const where: any = {};
    if (institutionId) {
      where.institutionId = institutionId;
    }

    const wallets = await this.prisma.wallet.findMany({
      where: {
        organization: where,
      },
    });

    const totalBalance = wallets.reduce((sum, w) => sum + w.balance, 0);
    const totalHeld = wallets.reduce((sum, w) => sum + w.heldBalance, 0);

    const recentPayments = await this.prisma.payment.findMany({
      where: {
        organization: where,
        status: 'COMPLETED',
      },
      take: 10,
      orderBy: { createdAt: 'desc' },
      include: {
        payer: {
          select: {
            id: true,
            email: true,
            username: true,
            profile: true,
          },
        },
        organization: true,
        journalEntry: {
          include: {
            lines: true,
          },
        },
      },
    });

    const totalDues = await this.prisma.due.count({
      where: {
        organization: where,
        status: 'ACTIVE',
      },
    });

    const totalPaidDues = await this.prisma.dueAssignment.count({
      where: {
        isPaid: true,
        due: {
          organization: where,
        },
      },
    });

    const totalPendingDues = await this.prisma.dueAssignment.count({
      where: {
        isPaid: false,
        due: {
          organization: where,
          status: 'ACTIVE',
        },
      },
    });

    const today = new Date();
    today.setHours(0, 0, 0, 0);

    const dailyTransactions = await this.prisma.transaction.count({
      where: {
        createdAt: { gte: today },
        wallet: {
          organization: where,
        },
      },
    });

    const platformFeeTotal = await this.prisma.journalLine.aggregate({
      where: {
        type: 'CREDIT',
        description: {
          in: ['Platform service fee', 'Heightt platform service fee'],
        },
        journalEntry: {
          payment: {
            status: 'COMPLETED',
            organization: where,
          },
        },
      },
      _sum: { amount: true },
    });

    const platformEarnings = platformFeeTotal._sum.amount ?? 0;

    return {
      totalBalance,
      totalHeld,
      totalWallets: wallets.length,
      platformEarnings: {
        amount: platformEarnings,
        amountFormatted: `₦${(platformEarnings / this.KOBO_PER_NAIRA).toFixed(
          2,
        )}`,
        currency: 'NGN',
        currencyUnit: 'KOBO',
      },
      dueStats: {
        total: totalDues,
        paid: totalPaidDues,
        pending: totalPendingDues,
        completionRate:
          totalDues > 0 ? Math.round((totalPaidDues / totalDues) * 100) : 0,
      },
      recentPayments: recentPayments.map((p) => ({
        id: p.id,
        amount: p.amount,
        amountFormatted: `₦${(p.amount / this.KOBO_PER_NAIRA).toFixed(2)}`,
        payer: p.payer?.username || 'Unknown',
        organization: p.organization?.name || 'Unknown',
        createdAt: p.createdAt,
        status: p.status,
        journalEntryId: p.journalEntryId,
      })),
      dailyTransactions,
    };
  }

